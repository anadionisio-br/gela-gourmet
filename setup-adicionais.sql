-- Execute este script no SQL Editor do Supabase antes de publicar as alterações.
create table if not exists public.adicionais (
  id bigint generated by default as identity primary key,
  nome text not null,
  preco numeric(10,2) not null default 5.00 check (preco >= 0),
  disponivel boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.adicionais enable row level security;

drop policy if exists "Leitura pública de adicionais ativos" on public.adicionais;
create policy "Leitura pública de adicionais ativos"
on public.adicionais for select
to anon, authenticated
using (true);

drop policy if exists "Admin gerencia adicionais" on public.adicionais;
create policy "Admin gerencia adicionais"
on public.adicionais for all
to authenticated
using (true)
with check (true);

insert into public.adicionais (nome, preco, disponivel)
select seed.nome, 5.00, true
from (values ('Nutella'), ('Ovomaltine'), ('Caramelo')) as seed(nome)
where not exists (
  select 1 from public.adicionais a where lower(a.nome) = lower(seed.nome)
);
